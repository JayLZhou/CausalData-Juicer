"""The four M1 export views compiled from validated causal units.

- sft.jsonl        minimal correction pairs (prompt -> corrected action)
- dpo.jsonl        original/repaired preference pairs
- memory.jsonl     failure-to-recovery units for agent memory
- regression.jsonl executable counterfactual cases (+ generated pytest file)

Only units at COUNTERFACTUAL_VALIDATED or above are exported for training
views; the tier is stamped on every row regardless.
"""
from __future__ import annotations

from pathlib import Path

from causal_data_juicer.compiler.common import (
    corrected_action,
    original_action,
    render_action,
    render_context,
    write_jsonl,
)
from causal_data_juicer.sdk.schemas import CausalUnit, Episode, EvidenceTier


def _episode_index(episodes: list[Episode]) -> dict[str, Episode]:
    return {ep.id: ep for ep in episodes}


def _exportable(units: list[CausalUnit]) -> list[CausalUnit]:
    return [u for u in units if u.tier >= EvidenceTier.COUNTERFACTUAL_VALIDATED]


def compile_sft(units: list[CausalUnit], episodes: list[Episode], out: Path) -> Path:
    eps = _episode_index(episodes)
    rows = []
    for u in _exportable(units):
        ep = eps[u.episode_id]
        rows.append({
            "unit_id": u.id,
            "task_id": u.task_id,
            "prompt": render_context(ep, u.effective_intervention().target_step),
            "completion": render_action(corrected_action(ep, u)),
            "evidence_tier": u.tier.name,
        })
    return write_jsonl(out, rows)


def compile_dpo(units: list[CausalUnit], episodes: list[Episode], out: Path) -> Path:
    eps = _episode_index(episodes)
    rows = []
    for u in _exportable(units):
        ep = eps[u.episode_id]
        rows.append({
            "unit_id": u.id,
            "task_id": u.task_id,
            "prompt": render_context(ep, u.effective_intervention().target_step),
            "chosen": render_action(corrected_action(ep, u)),
            "rejected": render_action(original_action(ep, u)),
            "evidence_tier": u.tier.name,
        })
    return write_jsonl(out, rows)


def compile_memory(units: list[CausalUnit], episodes: list[Episode], out: Path) -> Path:
    eps = _episode_index(episodes)
    rows = []
    for u in _exportable(units):
        ep = eps[u.episode_id]
        iv = u.effective_intervention()
        rows.append({
            "unit_id": u.id,
            "task_id": u.task_id,
            "task": ep.task_description,
            "failure": {
                "action": render_action(original_action(ep, u)),
                "outcome": u.original_outcome.detail,
            },
            "recovery": {
                "intervention_type": iv.type.value,
                "action": render_action(corrected_action(ep, u)),
                "rationale": iv.rationale,
            },
            "evidence_tier": u.tier.name,
        })
    return write_jsonl(out, rows)


def compile_regression(units: list[CausalUnit], episodes: list[Episode], out: Path) -> Path:
    """Executable counterfactual cases: enough information to re-fork the
    snapshot, re-apply the intervention and assert the flip.  A generated
    pytest file (test_regression.py next to the jsonl) drives them."""
    eps = _episode_index(episodes)
    rows = []
    for u in _exportable(units):
        ep = eps[u.episode_id]
        iv = u.effective_intervention()
        rows.append({
            "unit_id": u.id,
            "task_id": u.task_id,
            "episode_id": u.episode_id,
            "target_step": iv.target_step,
            "intervention": iv.model_dump(mode="json"),
            "expected": {"original_success": False, "intervened_success": True},
            "evidence_tier": u.tier.name,
        })
    path = write_jsonl(out, rows)
    (out.parent / "test_regression.py").write_text(_REGRESSION_TEST_TEMPLATE)
    return path


_REGRESSION_TEST_TEMPLATE = '''"""Auto-generated by causal_data_juicer.compiler — executable counterfactual cases.

Run from the run directory root:  pytest exports/test_regression.py
Each case re-forks the recorded snapshot, applies the stored intervention
and asserts the outcome flip still reproduces.
"""
import json
from pathlib import Path

import pytest

from causal_data_juicer.run_store import RunStore

RUN_DIR = Path(__file__).resolve().parent.parent
CASES = [json.loads(l) for l in (Path(__file__).parent / "regression.jsonl").open()]


@pytest.mark.parametrize("case", CASES, ids=[c["unit_id"] for c in CASES])
def test_counterfactual_flip(case, tmp_path):
    store = RunStore(RUN_DIR)
    ok, detail = store.replay_regression_case(case, scratch=tmp_path)
    assert ok, detail
'''


def compile_all(units: list[CausalUnit], episodes: list[Episode], out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    return {
        "sft": compile_sft(units, episodes, out_dir / "sft.jsonl"),
        "dpo": compile_dpo(units, episodes, out_dir / "dpo.jsonl"),
        "memory": compile_memory(units, episodes, out_dir / "memory.jsonl"),
        "regression": compile_regression(units, episodes, out_dir / "regression.jsonl"),
    }
